// Every few seconds the floor trembles: shake, and dust from the ceiling
const tremor: StageHooks = {
    step: (w) => {
        const f = Math.floor(w.time * 60);
        const phase = f % 420;
        if (phase > 360 && phase % 3 === 0) {
            shake(w, 1.6);
            const x = w.cam.x + range(w.fxRng, 0, 480);
            particle(w, "dust", x, w.cam.y + 20, range(w.fxRng, -0.2, 0.2), range(w.fxRng, 0.4, 1), 60, 0.02);
        }
    },
};

