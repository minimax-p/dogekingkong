export const GLYPH_W = 5;
export const GLYPH_H = 7;

export const textWidth = (s: string, gap = 1) => Math.max(0, s.length * (GLYPH_W + gap) - gap);

const tinted = new Map<string, HTMLCanvasElement>();

// Each glyph is rendered once per color into a strip for fast drawing
const strip = (color: string) => {
    let c = tinted.get(color);
    if (c) return c;
    const keys = Object.keys(G);
    c = document.createElement("canvas");
    c.width = keys.length * GLYPH_W;
    c.height = GLYPH_H;
    const g = c.getContext("2d")!;
    g.fillStyle = color;
    keys.forEach((k, i) => {
        const bits = G[k];
        for (let y = 0; y < GLYPH_H; y++) for (let x = 0; x < GLYPH_W; x++) if (bits[y * GLYPH_W + x] === "#") g.fillRect(i * GLYPH_W + x, y, 1, 1);
    });
    tinted.set(color, c);
    return c;
};

const INDEX = new Map(Object.keys(G).map((k, i) => [k, i]));

export const drawText = (
    g: CanvasRenderingContext2D,
    s: string,
    x: number,
    y: number,
    color: string,
    opts: { scale?: number; gap?: number; align?: "left" | "center" | "right"; shadow?: string } = {},
) => {
    const scale = opts.scale ?? 1;
    const gap = opts.gap ?? 1;
    const text = s.toUpperCase();
    const w = textWidth(text, gap) * scale;
    let cx = Math.round(opts.align === "center" ? x - w / 2 : opts.align === "right" ? x - w : x);
    const cy = Math.round(y);
    if (opts.shadow) drawText(g, s, x + scale, y + scale, opts.shadow, { ...opts, shadow: undefined });
    const img = strip(color);
    for (const ch of text) {
        const i = INDEX.get(ch);
        if (i !== undefined) g.drawImage(img, i * GLYPH_W, 0, GLYPH_W, GLYPH_H, cx, cy, GLYPH_W * scale, GLYPH_H * scale);
        cx += (GLYPH_W + gap) * scale;
    }
    return w;
};
